create table if not exists public.elvyn_products (
    id bigint generated by default as identity primary key,
    name text not null check (length(trim(name)) between 1 and 160),
    category text not null check (category in ('electronics', 'home', 'grocery', 'beauty', 'sports', 'men', 'women', 'kids', 'accessories')),
    price numeric(10, 2) not null check (price > 0),
    image_urls text[] not null default '{}',
    is_deal boolean not null default false,
    active boolean not null default true,
    created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
    key text primary key,
    value jsonb not null,
    updated_at timestamptz not null default now()
);

create table if not exists public.orders (
    id bigint generated always as identity primary key,
    status text not null default 'جديد' check (status in ('جديد', 'قيد التنفيذ', 'تم التسليم', 'ملغي')),
    customer_name text not null,
    customer_phone text not null,
    governorate text not null,
    city text not null,
    address text not null,
    shipping_method text not null,
    payment_method text not null,
    note text not null default '',
    subtotal numeric(10, 2) not null check (subtotal >= 0),
    shipping_fee numeric(10, 2) not null check (shipping_fee >= 0),
    total numeric(10, 2) not null check (total = subtotal + shipping_fee),
    items jsonb not null,
    created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
    user_id uuid primary key references auth.users (id) on delete cascade,
    created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
alter table public.elvyn_products enable row level security;
alter table public.site_settings enable row level security;
alter table public.orders enable row level security;

revoke all on public.admin_users from anon, authenticated;
grant select on public.elvyn_products, public.site_settings to anon, authenticated;
