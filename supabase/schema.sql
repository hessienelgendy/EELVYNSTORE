create or replace function public.create_elvyn_order(
    p_customer_name text,
    p_customer_phone text,
    p_governorate text,
    p_city text,
    p_address text,
    p_shipping_method text,
    p_payment_method text,
    p_note text,
    p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
    item jsonb;
    product_row public.elvyn_products%rowtype;
    quantity_value integer;
    discount_value numeric := 30;
    unit_price numeric;
    subtotal_value numeric := 0;
    shipping_value numeric;
    items_value jsonb := '[]'::jsonb;
    order_id_value bigint;
begin
    if p_items is null or jsonb_typeof(p_items) is distinct from 'array' then
        raise exception 'بيانات المنتجات في الطلب غير صالحة.';
    end if;

    if length(trim(coalesce(p_customer_name, ''))) not between 1 and 160
       or length(trim(coalesce(p_customer_phone, ''))) not between 7 and 32
       or length(trim(coalesce(p_governorate, ''))) not between 1 and 80
       or length(trim(coalesce(p_city, ''))) not between 1 and 120
       or length(trim(coalesce(p_address, ''))) not between 1 and 500
       or p_governorate not in (
            'القاهرة', 'الجيزة', 'الإسكندرية', 'القليوبية', 'البحيرة', 'مطروح',
            'دمياط', 'الدقهلية', 'كفر الشيخ', 'الغربية', 'المنوفية', 'الشرقية',
            'الإسماعيلية', 'بورسعيد', 'السويس', 'شمال سيناء', 'جنوب سيناء',
            'بني سويف', 'الفيوم', 'المنيا', 'أسيوط', 'سوهاج', 'قنا', 'الأقصر', 'أسوان'
       )
       or coalesce(p_shipping_method, '') not in ('توصيل سريع', 'توصيل عادي', 'استلام من المتجر')
       or coalesce(p_payment_method, '') not in ('انستا باي', 'فودافون كاش', 'الدفع عند الاستلام')
       or jsonb_array_length(p_items) not between 1 and 50 then
        raise exception 'بيانات الطلب غير مكتملة أو غير صالحة.';
    end if;

    select coalesce((value #>> '{}')::numeric, 30)
    into discount_value
    from public.site_settings
    where key = 'deal_discount';
    discount_value := least(100, greatest(0, coalesce(discount_value, 30)));

    for item in select value from jsonb_array_elements(p_items)
    loop
        if coalesce(item->>'product_id', '') !~ '^[0-9]+$'
           or coalesce(item->>'quantity', '') !~ '^[0-9]+$' then
            raise exception 'بيانات المنتجات في الطلب غير صالحة.';
        end if;

        quantity_value := (item->>'quantity')::integer;
        if quantity_value not between 1 and 99 then
            raise exception 'كمية المنتج غير صالحة.';
        end if;

        select *
        into product_row
        from public.elvyn_products
        where id = (item->>'product_id')::bigint
          and active = true
        for share;

        if not found then
            raise exception 'أحد المنتجات المطلوبة لم يعد متاحًا.';
        end if;

        unit_price := case
            when product_row.is_deal then greatest(1, round(product_row.price * (1 - discount_value / 100), 0))
            else product_row.price
        end;
        subtotal_value := subtotal_value + unit_price * quantity_value;
        items_value := items_value || jsonb_build_array(jsonb_build_object(
            'id', product_row.id,
            'name', product_row.name,
            'quantity', quantity_value,
            'price', unit_price,
            'image', product_row.image_urls[1],
            'category', product_row.category
        ));
    end loop;

    if p_shipping_method = 'استلام من المتجر' then
        shipping_value := 0;
    elsif p_governorate = 'بني سويف' then
        shipping_value := 0;
    elsif p_governorate = 'الفيوم' then
        shipping_value := 50;
    elsif p_governorate in ('القاهرة', 'الجيزة', 'المنيا') then
        shipping_value := 70;
    elsif p_governorate in ('القليوبية', 'المنوفية', 'الشرقية', 'الغربية') then
        shipping_value := 80;
    elsif p_governorate in ('البحيرة', 'دمياط', 'الدقهلية', 'كفر الشيخ', 'الإسماعيلية', 'بورسعيد', 'السويس', 'أسيوط') then
        shipping_value := 90;
    else
        shipping_value := 100;
    end if;

    insert into public.orders (
        customer_name, customer_phone, governorate, city, address,
        shipping_method, payment_method, note, subtotal, shipping_fee, total, items
    )
    values (
        trim(p_customer_name), trim(p_customer_phone), trim(p_governorate),
        trim(p_city), trim(p_address), p_shipping_method, p_payment_method,
        left(coalesce(p_note, ''), 1000), subtotal_value, shipping_value,
        subtotal_value + shipping_value, items_value
    )
    returning id into order_id_value;

    return jsonb_build_object(
        'id', order_id_value,
        'subtotal', subtotal_value,
        'shipping_fee', shipping_value,
        'total', subtotal_value + shipping_value,
        'items', items_value
    );
end;
$$;

