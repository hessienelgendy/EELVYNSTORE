create or replace function public.is_elvyn_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.admin_users
        where user_id = (select auth.uid())
    );
$$;

revoke all on function public.is_elvyn_admin() from public, anon;
grant execute on function public.is_elvyn_admin() to authenticated;

do $$
declare
    sequence_name text;
begin
    sequence_name := pg_get_serial_sequence('public.elvyn_products', 'id');
    if sequence_name is not null then
        execute format('revoke all on sequence %s from anon, authenticated', sequence_name);
        execute format('grant usage, select on sequence %s to authenticated', sequence_name);
    end if;

    sequence_name := pg_get_serial_sequence('public.orders', 'id');
    if sequence_name is not null then
        execute format('revoke all on sequence %s from anon, authenticated', sequence_name);
    end if;
end;
$$;

